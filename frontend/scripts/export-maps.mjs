// Converts the Tiled maps (tiled/*.tmx, tiled/interiors/*.tmx and
// tiled/regions/*.tmx) into
// src/levels/maps.js, which the game draws tile by tile.
//
//   npm run maps
//
// Layers named "Collisions" become the collision grid (any tile blocks),
// layers starting with "Foreground" are drawn over the characters and the
// object layer "Points" has named points (entrance, exit, spots, lights).

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "src/levels/maps.js");

// Tiled marks flipped tiles in the 3 highest bits of the gid
const GID_MASK = 0x1fffffff;

const attributes = (tag) =>
  Object.fromEntries(
    [...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [
      key,
      value,
    ]),
  );

function readTileset(tsxPath, firstgid) {
  const xml = readFileSync(tsxPath, "utf8");
  const tileset = attributes(xml.match(/<tileset[^>]*>/)[0]);
  const image = attributes(xml.match(/<image[^>]*>/)[0]);

  return {
    name: tileset.name,
    firstgid,
    tileWidth: Number(tileset.tilewidth),
    tileHeight: Number(tileset.tileheight),
    columns: Number(tileset.columns),
    count: Number(tileset.tilecount),
    // Served by Vite from public/
    image: `/tilesets/${basename(image.source)}`,
  };
}

function readMap(tmxPath) {
  const xml = readFileSync(tmxPath, "utf8");
  const map = attributes(xml.match(/<map[^>]*>/)[0]);
  const width = Number(map.width);
  const height = Number(map.height);

  const tilesets = [...xml.matchAll(/<tileset[^>]*\/>/g)].map(([tag]) => {
    const { firstgid, source } = attributes(tag);
    return readTileset(join(dirname(tmxPath), source), Number(firstgid));
  });
  const collisionTileset = tilesets.find((t) => t.name === "Collisions");

  const layers = [];
  let collisions = null;

  for (const [, tag, csv] of xml.matchAll(
    /<layer([^>]*)>\s*<data encoding="csv">([\s\S]*?)<\/data>/g,
  )) {
    const { name } = attributes(tag);
    const data = csv
      .split(",")
      .map((value) => value.trim())
      .filter(Boolean)
      .map(Number);

    if (name === "Collisions") {
      collisions = data.map((gid) => ((gid & GID_MASK) !== 0 ? 1 : 0));
      continue;
    }

    // Collision tiles out of the collision layer are only markers in Tiled
    const tiles = data.map((gid) =>
      collisionTileset &&
      (gid & GID_MASK) >= collisionTileset.firstgid &&
      (gid & GID_MASK) < collisionTileset.firstgid + collisionTileset.count
        ? 0
        : gid,
    );

    if (tiles.some(Boolean)) {
      layers.push({
        name,
        foreground: name.startsWith("Foreground"),
        data: tiles,
      });
    }
  }

  const points = {};
  for (const [, group, body] of xml.matchAll(
    /<objectgroup([^>]*)>([\s\S]*?)<\/objectgroup>/g,
  )) {
    if (attributes(group).name !== "Points") continue;
    for (const [tag] of body.matchAll(/<object[^>]*>/g)) {
      const object = attributes(tag);
      points[object.name] = {
        kind: object.type ?? object.class ?? "",
        x: Number(object.x),
        y: Number(object.y),
        width: Number(object.width ?? 0),
        height: Number(object.height ?? 0),
      };
    }
  }

  return {
    width,
    height,
    tileWidth: Number(map.tilewidth),
    tileHeight: Number(map.tileheight),
    tilesets: tilesets.filter((t) => t !== collisionTileset),
    layers,
    collisions: collisions ?? Array(width * height).fill(0),
    points,
  };
}

const maps = { village: readMap(join(root, "tiled/game-test-map.tmx")) };
for (const folder of ["interiors", "regions"]) {
  const dir = join(root, "tiled", folder);
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".tmx"))) {
    maps[basename(file, ".tmx")] = readMap(join(dir, file));
  }
}

// One line per layer keeps the file readable in diffs
const body = Object.entries(maps)
  .map(([id, { layers, collisions, ...map }]) => {
    const layerLines = layers
      .map(
        ({ data, ...layer }) =>
          `      { ...${JSON.stringify(layer)}, data: ${JSON.stringify(data)} },`,
      )
      .join("\n");
    return `  ${JSON.stringify(id)}: {
    ...${JSON.stringify(map)},
    layers: [
${layerLines}
    ],
    collisions: ${JSON.stringify(collisions)},
  },`;
  })
  .join("\n");

writeFileSync(
  output,
  `// Generated by scripts/export-maps.mjs from the Tiled maps in tiled/.
// Don't edit by hand: change the .tmx in Tiled and run \`npm run maps\`.

export const MAPS = {
${body}
};
`,
);

console.log(`Exported ${Object.keys(maps).join(", ")} to ${output}`);
